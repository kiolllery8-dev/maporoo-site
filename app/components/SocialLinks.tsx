// 頁尾的社群按鈕。網址在後台「前台文案 → 社群與聯絡」裡填。
//
// 沒填的欄位就不渲染那顆按鈕——連到空白的圖示比沒有圖示更糟。
// 圖示是內嵌 SVG：一顆按鈕不值得引一個 icon 套件，也不用多一次網路請求。

type Props = { heading: string; facebook: string; line: string; instagram: string };

export default function SocialLinks({ heading, facebook, line, instagram }: Props) {
  const items = [
    { key: "fb", href: facebook, label: "Facebook", icon: <FacebookIcon /> },
    { key: "line", href: line, label: "LINE", icon: <LineIcon /> },
    { key: "ig", href: instagram, label: "Instagram", icon: <InstagramIcon /> },
  ].filter((i) => i.href.trim().length > 0);

  if (items.length === 0) return null;

  return (
    <div className="social">
      {heading && <p className="t">{heading}</p>}
      <div className="social-row">
        {items.map((i) => (
          <a
            key={i.key}
            href={i.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={i.label}
            title={i.label}
          >
            {i.icon}
          </a>
        ))}
      </div>
    </div>
  );
}

